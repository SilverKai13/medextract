"""Corpus loading and tokenisation for token classification.

Loading is deliberately not a single `load_dataset` call. Both corpora this
project uses live in Hub repositories that contain a loader script and no data
files, and `datasets` 3.0 removed the ability to execute loader scripts. A
plain `load_dataset(hf_id)` therefore fails outright on any current install.

So `load_corpus` tries three sources in order and says which one it used. The
last of them downloads the same upstream files the official loader scripts
download, which makes the corpus identical to what a working `load_dataset`
would have produced and removes the dependency on any one Hub mechanism
staying available.
"""

from __future__ import annotations

import json
import logging
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING, Any

from medextract.config import DATASETS, REPO_ROOT, DatasetSpec
from medextract.labels import align_labels_with_tokens, build_label_maps, labels_to_ids

if TYPE_CHECKING:  # pragma: no cover - import only for type checkers
    from datasets import DatasetDict
    from transformers import PreTrainedTokenizerFast

log = logging.getLogger(__name__)

# Where the Hub's automatic parquet conversion of a script-only dataset lives.
# It is generated by the Hub rather than published by the dataset owner, so it
# is tried first for convenience but never relied on as the only source.
PARQUET_REVISION = "refs/convert/parquet"

DEFAULT_CORPUS_CACHE = REPO_ROOT / "data" / "corpora"


@dataclass
class PreparedData:
    tokenized: Any  # DatasetDict
    label_names: list[str]
    label2id: dict[str, int]
    id2label: dict[int, str]
    # Which of the three loaders produced the corpus, and how big each split
    # came out. Both go into the MLflow record: "which F1?" is only answerable
    # if the provenance of the data is part of the run.
    source: str = "unknown"
    split_sizes: dict[str, int] | None = None


def resolve_label_names(raw: DatasetDict, spec: DatasetSpec) -> list[str]:
    """Recover the BIO label vocabulary for a corpus.

    Prefers the dataset's own ClassLabel names so the ordering always matches
    the integers in the corpus. Falls back to the spec override for mirrors
    that ship the tags as bare ints.
    """
    split = next(iter(raw.values()))
    feature = split.features[spec.tags_column]
    names = getattr(getattr(feature, "feature", None), "names", None)
    if names:
        return list(names)
    if spec.label_names:
        return list(spec.label_names)
    raise ValueError(
        f"Cannot determine label names for {spec.hf_id}: the tags column is not a "
        "ClassLabel sequence and no label_names override is set in config.DATASETS."
    )


def parse_conll(text: str) -> list[tuple[list[str], list[str]]]:
    """Parse a two-column CoNLL TSV into (tokens, tags) sentences.

    One `token<TAB>tag` per line, blank line between sentences. Splitting on
    tab and taking the first two fields is exactly what the official
    ncbi_disease loader script does, so the token stream matches the corpus
    every published NCBI-Disease number is computed on.

    Empty sentences are dropped. The official script emits one at end-of-file
    when the file ends with a blank line; an example with no tokens has no gold
    spans and no predicted spans, so it cannot move entity-level F1 either way,
    and carrying it would just be copying a bug for the sake of it.
    """
    sentences: list[tuple[list[str], list[str]]] = []
    tokens: list[str] = []
    tags: list[str] = []

    for line in text.splitlines():
        if not line.strip():
            if tokens:
                sentences.append((tokens, tags))
                tokens, tags = [], []
            continue
        fields = line.split("\t")
        if len(fields) < 2:
            log.warning("skipping malformed CoNLL line: %r", line[:80])
            continue
        tokens.append(fields[0])
        tags.append(fields[1].strip())

    if tokens:
        sentences.append((tokens, tags))
    return sentences


def parse_tagged_jsonl(
    text: str, tokens_key: str, tags_key: str, label_names: list[str]
) -> list[tuple[list[str], list[str]]]:
    """Parse JSON-lines of {tokens: [...], tags: [...]} into (tokens, tags).

    Tags arrive as integers indexing `label_names` (the tner mirrors ship them
    that way), and are converted to strings here so both parsers hand back the
    same shape and the encoding step below has one path rather than two.
    """
    sentences: list[tuple[list[str], list[str]]] = []
    for line in text.splitlines():
        if not line.strip():
            continue
        record = json.loads(line)
        tokens = list(record[tokens_key])
        raw_tags = record[tags_key]
        tags = [label_names[t] if isinstance(t, int) else str(t) for t in raw_tags]
        if len(tokens) != len(tags):
            raise ValueError(
                f"Corrupt record: {len(tokens)} tokens but {len(tags)} tags in {line[:120]!r}"
            )
        if tokens:
            sentences.append((tokens, tags))
    return sentences


def _download_text(url: str, cache_dir: Path) -> str:
    """Fetch a corpus file, caching it so a re-run costs nothing."""
    import httpx

    cache_dir.mkdir(parents=True, exist_ok=True)
    cached = cache_dir / url.rsplit("/", 1)[-1]
    if cached.exists():
        log.info("using cached %s", cached)
        return cached.read_text(encoding="utf-8")

    log.info("downloading %s", url)
    response = httpx.get(url, timeout=60.0, follow_redirects=True)
    response.raise_for_status()
    cached.write_text(response.text, encoding="utf-8")
    return response.text


def load_from_direct_urls(spec: DatasetSpec, cache_dir: str | Path | None = None) -> DatasetDict:
    """Build a DatasetDict from the corpus files the loader script would fetch.

    The result carries a real ClassLabel feature rather than bare ints, so
    `resolve_label_names` recovers the vocabulary from the dataset itself and
    the rest of the pipeline cannot tell this apart from a Hub load.
    """
    from datasets import ClassLabel, Dataset, DatasetDict, Features, Sequence, Value

    if not spec.direct_urls:
        raise ValueError(f"{spec.hf_id} has no direct_urls configured.")
    if not spec.label_names:
        raise ValueError(
            f"{spec.hf_id} has direct_urls but no label_names; the label ordering "
            "cannot be recovered from a raw corpus file."
        )

    label_names = list(spec.label_names)
    root = Path(cache_dir) if cache_dir else DEFAULT_CORPUS_CACHE
    corpus_cache = root / spec.hf_id.replace("/", "__")

    features = Features(
        {
            "id": Value("string"),
            spec.tokens_column: Sequence(Value("string")),
            spec.tags_column: Sequence(ClassLabel(names=label_names)),
        }
    )

    splits: dict[str, Any] = {}
    for split, url in spec.direct_urls.items():
        text = _download_text(url, corpus_cache)
        if spec.direct_format == "conll":
            sentences = parse_conll(text)
        elif spec.direct_format == "jsonl":
            sentences = parse_tagged_jsonl(text, spec.tokens_column, spec.tags_column, label_names)
        else:
            raise ValueError(f"Unknown direct_format {spec.direct_format!r}")

        unknown = {t for _, tags in sentences for t in tags} - set(label_names)
        if unknown:
            raise ValueError(
                f"{spec.hf_id} {split} split contains tags {sorted(unknown)} that are not "
                f"in the configured label set {label_names}. Fix config.DATASETS."
            )

        splits[split] = Dataset.from_dict(
            {
                "id": [str(i) for i in range(len(sentences))],
                spec.tokens_column: [tokens for tokens, _ in sentences],
                spec.tags_column: [[label_names.index(t) for t in tags] for _, tags in sentences],
            },
            features=features,
        )
        log.info("%s %s split: %d sentences", spec.hf_id, split, len(sentences))

    return DatasetDict(splits)


def load_corpus(
    dataset_key: str = "ncbi_disease", cache_dir: str | None = None
) -> tuple[DatasetDict, DatasetSpec, str]:
    """Load a corpus, returning it with the name of the source that produced it.

    Sources are tried in order of how little they assume:

    1. The Hub's auto-generated parquet conversion of the repo.
    2. A plain Hub load, in case the repo has since gained real data files.
    3. The upstream corpus files the loader script downloads.

    A failure of one is logged and the next is tried; only exhausting all three
    is an error, and it names every attempt so the cause is visible.
    """
    from datasets import load_dataset

    if dataset_key not in DATASETS:
        raise KeyError(f"Unknown dataset {dataset_key!r}. Known: {sorted(DATASETS)}")
    spec = DATASETS[dataset_key]

    attempts: list[str] = []
    raw = None
    source = "unknown"

    for name, loader in (
        (
            f"hub-parquet ({spec.hf_id}@{PARQUET_REVISION})",
            lambda: load_dataset(
                spec.hf_id, spec.config_name, cache_dir=cache_dir, revision=PARQUET_REVISION
            ),
        ),
        (
            f"hub ({spec.hf_id})",
            lambda: load_dataset(spec.hf_id, spec.config_name, cache_dir=cache_dir),
        ),
        (
            "direct-download",
            lambda: load_from_direct_urls(spec, cache_dir),
        ),
    ):
        try:
            raw = loader()
            source = name
            log.info("loaded %s from %s", dataset_key, name)
            break
        except Exception as exc:  # every source is optional; the last one failing is the error
            attempts.append(f"{name}: {type(exc).__name__}: {exc}")
            log.warning("corpus source %s unavailable (%s)", name, type(exc).__name__)

    if raw is None:
        joined = "\n  ".join(attempts)
        raise RuntimeError(f"Could not load {dataset_key!r} from any source:\n  {joined}")

    if spec.validation_split not in raw:
        log.warning(
            "%s has no %r split; holding out 10%% of train instead.",
            spec.hf_id,
            spec.validation_split,
        )
        split = raw["train"].train_test_split(test_size=0.1, seed=13)
        raw["train"] = split["train"]
        raw[spec.validation_split] = split["test"]

    return raw, spec, source


def build_tokenize_fn(
    tokenizer: PreTrainedTokenizerFast,
    spec: DatasetSpec,
    label_names: list[str],
    *,
    max_length: int = 256,
    label_all_subwords: bool = False,
):
    """Return a batched map() function producing input_ids/attention_mask/labels."""
    from medextract.tokenization import require_word_alignment

    label2id, _ = build_label_maps(label_names)

    # word_ids() is the only reliable way to map word labels onto subwords.
    require_word_alignment(tokenizer, purpose="label alignment")

    def tokenize_and_align(batch: dict[str, list]) -> dict[str, list]:
        encoded = tokenizer(
            batch[spec.tokens_column],
            is_split_into_words=True,
            truncation=True,
            max_length=max_length,
        )

        all_labels: list[list[int]] = []
        for i, tags in enumerate(batch[spec.tags_column]):
            word_labels = [label_names[t] if isinstance(t, int) else t for t in tags]
            aligned = align_labels_with_tokens(
                encoded.word_ids(batch_index=i),
                word_labels,
                label_all_subwords=label_all_subwords,
            )
            all_labels.append(labels_to_ids(aligned, label2id))

        encoded["labels"] = all_labels
        return encoded

    return tokenize_and_align


def prepare(
    tokenizer: PreTrainedTokenizerFast,
    dataset_key: str = "ncbi_disease",
    *,
    max_length: int = 256,
    label_all_subwords: bool = False,
    cache_dir: str | None = None,
) -> PreparedData:
    raw, spec, source = load_corpus(dataset_key, cache_dir=cache_dir)
    label_names = resolve_label_names(raw, spec)
    label2id, id2label = build_label_maps(label_names)

    tokenize_fn = build_tokenize_fn(
        tokenizer,
        spec,
        label_names,
        max_length=max_length,
        label_all_subwords=label_all_subwords,
    )
    tokenized = raw.map(
        tokenize_fn,
        batched=True,
        remove_columns=next(iter(raw.values())).column_names,
        desc="tokenising",
    )
    return PreparedData(
        tokenized,
        label_names,
        label2id,
        id2label,
        source=source,
        split_sizes={name: len(split) for name, split in tokenized.items()},
    )
